#include <iostream>
int main() {
    int size;
    std::cout << "Введіть розмір масиву: ";
    std::cin >> size; // Розмір визначається ПІД ЧАС роботи програми!

// Виділення пам'яті під масив
    int *arr = new int[size];

// Робота з масивом (синтаксис такий самий, як у звичайного)
    arr[0] = 10;
    arr[1] = 20;

// Звільнення пам'яті (ОБОВ'ЯЗКОВО З ДУЖКАМИ!)
    delete[] arr;
    arr = nullptr;
}