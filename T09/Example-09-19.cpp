#include <iostream>
#include <fstream> // Бібліотека для роботи з файлами в C++
#include <cstdlib> // Для генерації випадкових чисел (rand, srand)
#include <ctime>   // Для ініціалізації генератора випадкових чисел від часу

using namespace std;

int main() {
    // 1. Створюємо об'єкт класу ofstream (output file stream) для запису у файл
    ofstream outFile("input.txt");

    // 2. Перевіряємо, чи успішно відкрився/створився файл
    if (!outFile.is_open()) {
        cerr << "Помилка: не вдалося створити файл input.txt!" << endl;
        return 1;
    }

    // 3. Записуємо кілька конкретних (заздалегідь визначених) пар чисел
    outFile << "10 25\n";
    outFile << "-5 15\n";
    outFile << "100 200\n";
    outFile << "42 0\n";

    // --- ОПЦІОНАЛЬНО --- 
    // Можна також згенерувати кілька випадкових пар чисел для масового тестування
    srand(time(0)); // Ініціалізуємо генератор випадкових чисел

    // Генеруємо 5 випадкових пар чисел від 1 до 50
    for (int i = 0; i < 5; i++) {
        int a = rand() % 50 + 1;
        int b = rand() % 50 + 1;
        outFile << a << " " << b << "\n";
    }
    // -------------------

    // 4. Закриваємо файл (важливий крок для збереження даних)
    outFile.close();

    cout << "Файл input.txt успішно згенеровано! Можна запускати основну програму." << endl;

    return 0;
}