#include <iostream>
#include <cstdio> // Підключаємо бібліотеку C для введення-виведення

int main() {
    // 1. Оголошуємо вказівник і намагаємося відкрити файл для запису
    FILE* myFile = fopen("test.txt", "w");

    // 2. Перевіряємо, чи успішно відкрився файл
    if (myFile == NULL) {
        std::cerr << "Помилка: не вдалося відкрити файл!" << std::endl;
        return 1; // Завершуємо роботу з кодом помилки
    }

    // 3. Тут буде логіка роботи з файлом (запис/читання)
    std::cout << "Файл test.txt успішно відкрито." << std::endl;
    // ...

    // 4. ОБОВ'ЯЗКОВО закриваємо файл після завершення роботи
    fclose(myFile);
    std::cout << "Файл закрито." << std::endl;

    return 0;
}