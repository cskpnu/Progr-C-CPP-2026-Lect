#include <iostream>

int main() {
    int age;

    // Використання std::cout для звичайного діалогу
    std::cout << "Будь ласка, введіть ваш вік: ";

    // Використання std::cin для зчитування даних у змінну
    std::cin >> age;

    // Перевірка на помилку введення
    if (std::cin.fail() || age < 0) {
        // Використання std::cerr для повідомлення про критичну помилку
        std::cerr << "ПОМИЛКА: Некоректний формат віку або від'ємне значення!\n";
        return 1; // Завершуємо програму з кодом помилки
    }

    std::cout << "Ваш вік збережено: " << age << " років.\n";

    return 0; // Нормальне завершення
}
